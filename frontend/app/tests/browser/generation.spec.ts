test('uploaded 1025-word full lyrics are blocked without dispatch and shortening recovers the same song', async ({ page }, testInfo) => {
  test.setTimeout(60000);
  const lines = Array.from({ length: 64 }, (_, i) => String.fromCharCode(0x4e00 + i) + '词'.repeat(i === 63 ? 16 : 15));
  const text = lines.join('\n'), dispatched: string[] = [];
  page.on('request', request => { if (request.method() === 'POST' && /\/generations$/.test(new URL(request.url()).pathname)) dispatched.push(request.url()); });
  await page.goto('/'); await create(page, 'TXT超限后恢复');
  await page.getByLabel('上传歌词 TXT', { exact: true }).setInputFiles({ name: 'words257.txt', mimeType: 'text/plain', buffer: Buffer.from(text) });
  const generate = page.getByRole('button', { name: /模拟生成(?:全文歌词| 60 秒)候选/ });
  await expect(page.getByTestId('lyric-selection-count')).toContainText('1025/1024');
  await expect(page.getByTestId('ai-input-warning')).toContainText('1025个字词');
  await expect(generate).toBeDisabled(); expect(dispatched).toHaveLength(0);
  const shortened = lines.slice(0, -1).join('\n');
  await page.getByRole('textbox', { name: '歌词全文', exact: true }).fill(shortened);
  await expect(page.getByTestId('lyric-selection-count')).toContainText('1008/1024');
  await expect(generate).toBeEnabled(); await generate.click();
  await expect(page.getByTestId('generation-status').first()).toContainText('候选已保存');
  await page.getByText('查看候选的歌词与音符对应', { exact: true }).click();
  await expect(page.getByTestId('lyric-unit')).toHaveCount(1008);
  expect(dispatched).toHaveLength(1);
  await expect(page.getByRole('textbox', { name: '歌词全文', exact: true })).toHaveValue(shortened);
  await page.getByRole('button', { name: '本次不使用歌词', exact: true }).click();
  await page.getByRole('textbox', { name: '歌词全文', exact: true }).fill('');
  await expect(generate).toBeEnabled(); await generate.click();
  await expect(page.getByTestId('generation-status').first()).toContainText('候选已保存');
  await expect(page.getByText('查看候选的歌词与音符对应', { exact: true })).toHaveCount(0);
  expect(dispatched).toHaveLength(2);
  await page.screenshot({ path: testInfo.outputPath('lyrics-input-fixed.png'), fullPage: true });
});
