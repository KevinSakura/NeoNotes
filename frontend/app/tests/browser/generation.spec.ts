test('preserved recording with lyrics survives generation and edited anchor blocks approval', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await create(page, '第四阶段保留与试唱');
  await page.getByRole('button', { name: '● 开始录制', exact: true }).click();
  await expect(page.getByRole('button', { name: '■ 停止录制', exact: true })).toBeVisible();
  for (const key of ['a', 's', 'd']) {
    await page.keyboard.down(key); await page.waitForTimeout(300); await page.keyboard.up(key); await page.waitForTimeout(180);
  }
  await page.getByRole('button', { name: '■ 停止录制', exact: true }).click();
  await expect(page.getByTestId('record-info')).toContainText('3 个音符');
  await page.getByRole('combobox', { name: '旋律参与方式', exact: true }).selectOption('preserve');
  await page.getByLabel('上传歌词 TXT', { exact: true }).setInputFiles({ name: 'stage4.txt', mimeType: 'text/plain', buffer: Buffer.from('昨日轻轻放下\n脚步迎向朝阳') });
  await page.getByRole('button', { name: '模拟生成全文歌词候选', exact: true }).click();
  await expect(page.getByTestId('reference-lock')).toContainText('程序保留 3 个');
  const applyResponse = page.waitForResponse(response => response.request().method() === 'POST' && /\/generations\/[a-f0-9]+\/apply$/.test(new URL(response.url()).pathname));
  await page.getByRole('button', { name: '采用到编辑器', exact: true }).click();
  const applied = await (await applyResponse).json();
  const firstSungId = applied.revision.state.composition.lyrics_alignment[0].note_ids[0];
  const firstSungIndex = applied.revision.state.score.tracks[0].notes.findIndex((note: {id: string}) => note.id === firstSungId);
  expect(firstSungIndex).toBeGreaterThan(2);
  await page.getByRole('button', { name: '去保存与导出 →', exact: true }).click();
  await expect(page.getByTestId('assessment-report')).toContainText('原演奏保留约束');
  await page.getByRole('button', { name: '听第 1 行歌词', exact: true }).click();
  await expect.poll(async () => Number(await page.getByTestId('playback-audio-level').getAttribute('value')), { intervals: [50, 100, 200] }).toBeGreaterThan(0.0001);
  await expect(page.locator('[data-testid="lyric-unit"][data-active="true"]')).not.toHaveCount(0);
  await page.getByRole('button', { name: '02 演奏与编辑', exact: true }).click();
  await expect(page.locator('.floating-player')).toHaveCount(0);
  await page.getByTestId('roll-note').first().click();
  await page.getByRole('spinbutton', { name: '力度', exact: true }).fill('44');
  await page.getByRole('button', { name: '应用修改', exact: true }).click();
  await page.getByRole('button', { name: '保存歌曲', exact: true }).click();
  await expect(page.getByTestId('save-state')).toContainText('已写入歌曲目录');
  await page.getByRole('button', { name: '去保存与导出 →', exact: true }).click();
  await expect(page.getByTestId('assessment-report')).toContainText('没有完整保留原演奏');
  await expect(page.getByRole('button', { name: '记录审核通过', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '重新核对当前版本', exact: true }).click();
  await expect(page.getByTestId('assessment-report')).toContainText('没有完整保留原演奏');
  await page.getByRole('button', { name: '02 演奏与编辑', exact: true }).click();
  // Prefix and intro are unbound; remove the actual first sung note.
  await page.getByTestId('roll-note').nth(firstSungIndex).click();
  await page.getByRole('button', { name: '删除音符', exact: true }).click();
  await page.getByRole('button', { name: '保存歌曲', exact: true }).click();
  await page.getByRole('button', { name: '去保存与导出 →', exact: true }).click();
  await expect(page.getByTestId('lyrics-alignment')).toContainText('歌词对应的音符已删除');
  await expect(page.getByRole('button', { name: '听第 1 行歌词', exact: true })).toBeDisabled();
  await expect(page.getByTestId('assessment-report')).toContainText('歌词对应的音符已删除');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('needs-edit-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});

