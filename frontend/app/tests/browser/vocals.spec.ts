import { expect, test } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';

test('mixed lyrics show exact positions while settings save and reload independently', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const token = (await (await page.request.get('/api/session')).json()).token;
  const headers = { 'X-Session-Token': token };
  const initial = await (await page.request.post('/api/projects', { headers, data: { name: '隔离中英歌词设置' } })).json();
  const original = await (await page.request.get('/api/test-server/vocal-fixture')).json();
  const mixed = structuredClone(original);
  const lines = mixed.inputs.lyrics_text.split('\n');
  lines[0] = ['Why', ...Array.from(lines[0] as string).slice(1)].join(' ');
  lines[1] = ['Yes', ...Array.from(lines[1] as string).slice(1)].join(' ');
  mixed.inputs.lyrics_text = lines.join('\n');
  mixed.composition.lyrics_alignment[0].text = 'Why';
  mixed.composition.lyrics_alignment[8].text = 'Yes';
  const savedResponse = await page.request.put(`/api/projects/${initial.id}`, { headers, data: { base_revision: initial.current_revision, label: '隔离双语固定谱', state: mixed } });
  expect(savedResponse.ok()).toBe(true);
  const saved = await savedResponse.json();
  await page.reload();
  await page.getByRole('button', { name: /隔离中英歌词设置.*本地歌曲/ }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  const panel = page.getByRole('article', { name: '人声演唱', exact: true });
  const check = panel.getByTestId('vocal-score-check');
  await expect(check).toContainText('共有 2 处字词');
  await expect(check).toContainText('第 1 行 · 第 1 字词 · Why');
  await expect(check).toContainText('第 2 行 · 第 1 字词 · Yes');
  await expect(panel.getByRole('button', { name: '生成演唱 / 更新合听', exact: true })).toBeDisabled();
  await panel.getByLabel('人声音量', { exact: true }).fill('0.6');
  const response = page.waitForResponse(result => result.url().endsWith(`/projects/${initial.id}/vocal-settings`) && result.request().method() === 'POST');
  await panel.getByRole('button', { name: '保存演唱设置', exact: true }).click();
  expect((await response).status()).toBe(200);
  await expect(panel.getByText('演唱设置已保存。', { exact: true })).toBeVisible();
  expect((await (await page.request.get(`/api/projects/${initial.id}/vocals`)).json()).items).toEqual([]);
  expect(await (await page.request.get(`/api/projects/${initial.id}`)).json()).toEqual(saved);
  await page.reload();
  await page.getByRole('button', { name: /隔离中英歌词设置.*本地歌曲/ }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  await expect(panel.getByLabel('人声音量', { exact: true })).toHaveValue('0.6');
  await expect(check).toContainText('共有 2 处字词');
  await panel.getByText('修正读错的字', { exact: true }).click();
  await expect(panel.getByLabel('修正哪个字', { exact: true }).getByRole('option', { name: /Why|Yes/ })).toHaveCount(0);
  // A separately saved Chinese score becomes ready; the mixed revision is preserved.
  const repaired = await page.request.put(`/api/projects/${initial.id}`, { headers, data: { base_revision: saved.current_revision, label: '隔离中文固定谱', state: original } });
  expect(repaired.ok()).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: /隔离中英歌词设置.*本地歌曲/ }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  await expect(check).toHaveCount(0);
  await expect(panel.getByRole('button', { name: '生成演唱 / 更新合听', exact: true })).toBeEnabled();
  expect(errors).toEqual([]);
});

test('real singer generation, synchronized stems, pronunciation, remix, cancellation and trash restore', async ({ page }, testInfo) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const token = (await (await page.request.get('/api/session')).json()).token;
  const headers = { 'X-Session-Token': token };
  const initial = await (await page.request.post('/api/projects', { headers, data: { name: '隔离真实歌手试听' } })).json();
  const state = await (await page.request.get('/api/test-server/vocal-fixture')).json();
  const savedResponse = await page.request.put(`/api/projects/${initial.id}`, { headers, data: { base_revision: initial.current_revision, label: '手工固定谱测试', state } });
  expect(savedResponse.ok()).toBe(true);
  const saved = await savedResponse.json();
  await page.reload();
  await page.getByRole('button', { name: /隔离真实歌手试听.*本地歌曲/ }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  const panel = page.getByRole('article', { name: '人声演唱', exact: true });
  const generate = panel.getByRole('button', { name: '生成演唱 / 更新合听', exact: true });
  await expect(generate).toBeEnabled({ timeout: 15000 });
  await panel.getByText('修正读错的字', { exact: true }).click();
  await panel.getByLabel('修正哪个字', { exact: true }).selectOption('1:0');
  await panel.getByLabel('正确读音拼音', { exact: true }).fill('chong');
  await panel.getByRole('button', { name: '应用读音修正', exact: true }).click();
  await generate.click();
  await expect(panel.getByTestId('vocal-status').first()).toContainText('已保存', { timeout: 60000 });
  const jobs = async () => (await (await page.request.get(`/api/projects/${initial.id}/vocals`)).json()).items;
  const first = (await jobs())[0];
  expect(first.mock).toBe(false);
  expect(first.settings.pronunciations).toEqual([{ line_index: 1, unit_index: 0, pinyin: 'chong' }]);
  expect(first.engine.phrases.flatMap((p: {notes: unknown[]}) => p.notes)).toHaveLength(28);
  expect(first.removed_guide_note_ids).toHaveLength(28);
  const asset = (job: string, name: string) => `/api/projects/${initial.id}/vocals/${job}/assets/${name}`;
  const hash = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex');
  const before = hash(await (await page.request.get(asset(first.id, 'vocal.wav'))).body());
  await page.evaluate(() => {
    const tracking = window as Window & { vocalStarts?: { when: number; context: number }[]; vocalContexts?: BaseAudioContext[] };
    tracking.vocalStarts = []; tracking.vocalContexts = [];
    const original = AudioBufferSourceNode.prototype.start;
    AudioBufferSourceNode.prototype.start = function(when = 0, offset = 0, duration?: number) {
      if (!tracking.vocalContexts!.includes(this.context)) tracking.vocalContexts!.push(this.context);
      tracking.vocalStarts!.push({ when, context: tracking.vocalContexts!.indexOf(this.context) });
      if (duration === undefined) original.call(this, when, offset); else original.call(this, when, offset, duration);
    };
  });
  await panel.getByRole('button', { name: '人声与伴奏合听', exact: true }).click();
  await expect(panel.getByText(/演唱试听 \d+\.\d \/ /)).toBeVisible();
  const starts = await page.evaluate(() => (window as Window & { vocalStarts?: { when: number; context: number }[] }).vocalStarts!);
  expect(starts).toHaveLength(2);
  expect(starts[0]).toEqual(starts[1]);
  await panel.getByRole('button', { name: '停止演唱试听', exact: true }).click();
  for (const label of ['听人声', '听伴奏']) {
    await panel.getByRole('button', { name: label, exact: true }).click();
    await expect(panel.getByRole('button', { name: '停止演唱试听', exact: true })).toBeEnabled();
    await panel.getByRole('button', { name: '停止演唱试听', exact: true }).click();
  }
  for (const [label, filename] of [['人声 WAV', 'vocal.wav'], ['伴奏 WAV', 'accompaniment.wav'], ['合听 WAV', 'mix.wav'], ['合听 MP3', 'mix.mp3'], ['OpenUtau 工程', 'singing.ustx']]) {
    const download = page.waitForEvent('download');
    await panel.getByRole('link', { name: label, exact: true }).click();
    const file = await download;
    expect(file.suggestedFilename()).toMatch(/^neonote-/);
    expect(hash(await readFile((await file.path())!))).toBe(first.files[filename].sha256);
  }
  await panel.getByLabel('人声音量', { exact: true }).fill('0.6');
  await generate.click();
  await expect(panel.getByTestId('vocal-status').first()).toContainText('复用原干声与伴奏', { timeout: 20000 });
  await expect(panel.getByTestId('vocal-status').first()).toContainText('已保存', { timeout: 20000 });
  const remix = (await jobs())[0];
  expect(remix.reused_from).toBe(first.id);
  expect(remix.files['vocal.wav'].sha256).toBe(before);
  await page.reload();
  await page.getByRole('button', { name: /隔离真实歌手试听.*本地歌曲/ }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  await expect(panel.getByLabel('人声音量', { exact: true })).toHaveValue('0.6');
  await panel.getByText('运行设备与资源', { exact: true }).click();
  await panel.getByLabel('演唱运行方式', { exact: true }).selectOption('CPU');
  await generate.click();
  await expect(panel.getByTestId('vocal-status').first()).toContainText('生成演唱片段', { timeout: 15000 });
  await panel.getByRole('button', { name: '取消演唱', exact: true }).click();
  await expect(panel.getByTestId('vocal-status').first()).toContainText('已取消', { timeout: 15000 });
  const cancelled = (await jobs())[0];
  expect(cancelled.status).toBe('cancelled');
  expect(cancelled.files).toEqual({});
  expect(hash(await (await page.request.get(asset(first.id, 'vocal.wav'))).body())).toBe(before);
  expect(await (await page.request.get(`/api/projects/${initial.id}`)).json()).toEqual(saved);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('vocal-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.screenshot({ path: testInfo.outputPath('vocal-desktop.png'), fullPage: true });
  await panel.getByRole('button', { name: '人声与伴奏合听', exact: true }).click();
  await expect(panel.getByRole('button', { name: '停止演唱试听', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: `删除歌曲「隔离真实歌手试听」（${initial.id.slice(0, 8)}）`, exact: true }).click();
  await expect(panel.getByRole('button', { name: '停止演唱试听', exact: true })).toBeDisabled();
  await page.getByRole('dialog', { name: '删除这首歌曲？', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '删除这首歌曲？', exact: true })).toHaveCount(0);
  expect((await page.request.get(asset(first.id, 'vocal.wav'))).status()).toBe(404);
  await page.getByRole('button', { name: '回收站', exact: true }).click();
  const trash = page.getByRole('dialog', { name: '歌曲回收站', exact: true });
  await trash.getByRole('button', { name: `恢复歌曲「隔离真实歌手试听」（${initial.id.slice(0, 8)}）`, exact: true }).click();
  await expect(trash).toContainText('已恢复，请从歌曲列表打开');
  await trash.getByRole('button', { name: '关闭窗口', exact: true }).click();
  expect(hash(await (await page.request.get(asset(first.id, 'vocal.wav'))).body())).toBe(before);
  await page.getByRole('button', { name: /隔离真实歌手试听.*本地歌曲/ }).click();
  await page.getByRole('textbox', { name: '主题', exact: true }).fill('另一个保存版本');
  await page.getByRole('button', { name: '保存歌曲', exact: true }).click();
  await page.getByRole('button', { name: /03\s*保存与导出/ }).click();
  await expect(panel.getByTestId('vocal-status').filter({ hasText: '已保存' }).first()).toContainText('非当前保存版本');
  expect(errors).toEqual([]);
});
