test('long shared plan, mock block failure, explicit retry and whole candidate only', async ({ page }) => {
  test.setTimeout(90000);
  let offset = 0;
  const text = Array.from({ length: 64 }, (_, row) => {
    const length = [20, 12, 18, 14][row % 4];
    const line = Array.from({ length }, () => String.fromCodePoint(0x4e00 + offset++)).join('');
    return line;
  }).join('\n');
  const { id, ai, headers, identity } = await open(page, '隔离长文分块', text);
  await expect(ai.getByTestId('phrase-budget')).toContainText('1024 字词');
  await expect(ai.getByTestId('phrase-budget')).toContainText('最多 17 次请求');
  await page.request.post('/api/test-server/phrase-control', { headers, data: { run_id: identity.run_id, project_id: id, fail_block: 1 } });
  await ai.getByRole('button', { name: '模拟生成全文歌词候选', exact: true }).click();
  await expect(ai.getByText('隔离模拟服务：这个分块失败。', { exact: true })).toBeVisible({ timeout: 20000 });
  const failed = (await (await page.request.get('/api/projects/' + id + '/generations')).json()).items[0];
  expect(failed.status).toBe('failed');
  expect(failed.request_count).toBe(0);
  expect(failed.simulated_requests).toBe(3);
  expect((await page.request.get('/api/projects/' + id + '/generations/' + failed.id + '/candidate')).status()).toBe(409);
  await page.request.post('/api/test-server/phrase-control', { headers, data: { run_id: identity.run_id, project_id: id, fail_block: null } });
  await ai.getByRole('button', { name: /查看重试预算/ }).first().click();
  await expect(ai.getByTestId('phrase-retry-budget')).toContainText('复用 1 个');
  await ai.getByRole('button', { name: '按此预算显式重试', exact: true }).click();
  await expect(ai.getByTestId('phrase-contract')).toBeVisible({ timeout: 30000 });
  const jobs = (await (await page.request.get('/api/projects/' + id + '/generations')).json()).items;
  expect(jobs[0].status).toBe('completed');
  expect(jobs[0].retry_of).toBe(failed.id);
  expect(jobs[0].reused_blocks).toBe(1);
  expect(jobs[0].request_count).toBe(0);
  expect(jobs.find((j: { id: string }) => j.id === failed.id).status).toBe('failed');
  const candidate = await (await page.request.get('/api/projects/' + id + '/generations/' + jobs[0].id + '/candidate')).json();
  expect(candidate.composition.lyrics_alignment).toHaveLength(1024);
  expect(candidate.composition.v2.phrase_layout.length).toBeGreaterThan(64);
});
