import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';

async function open(page: Page, name: string, lyrics: string) {
  await page.goto('/');
  const identity = await (await page.request.get('/api/test-server')).json();
  const token = (await (await page.request.get('/api/session')).json()).token;
  const headers = { 'X-Session-Token': token };
  const initial = await (await page.request.post('/api/projects', { headers, data: { name } })).json();
  const state = structuredClone(initial.revision.state);
  state.inputs.lyrics_text = lyrics;
  state.inputs.selected_lines = lyrics.split('\n').map((s, i) => s.trim() ? i : -1).filter(i => i >= 0);
  const response = await page.request.put('/api/projects/' + initial.id, { headers, data: { base_revision: initial.current_revision, state } });
  expect(response.ok()).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: new RegExp(name + '.*本地歌曲') }).click();
  const ai = page.getByTestId('ai-generate');
  await expect(ai.getByLabel('歌词谱曲方式')).toHaveValue('lyric-motifs-v1');
  await ai.getByLabel('歌词谱曲方式').selectOption('lyric-phrases-v2');
  await expect(ai.getByTestId('phrase-budget')).toContainText('试验入口');
  return { id: initial.id as string, headers, identity, ai };
}

