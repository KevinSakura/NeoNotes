  // Projects are listed after reload; reopening never relies on browser storage.
  await page.getByRole('button', { name: /浏览器验收 A.*本地歌曲/ }).click();
  await expect(page.getByRole('textbox', { name: '主题', exact: true })).toHaveValue('悲伤歌词，明亮曲风a');
  await expect(page.getByTestId('record-info')).toContainText('2 个音符');
  await expect(page.getByTestId('lyric-selection-count')).toContainText('使用 4 行');
  await page.getByRole('button', { name: /02\s*演奏与编辑/ }).click();
  await expect(page.getByTestId('roll-note')).toHaveCount(2);
  await page.getByRole('button', { name: '↶ 撤销', exact: true }).click();
  await expect(page.getByTestId('roll-note')).toHaveCount(0);
  await page.getByRole('button', { name: '↷ 重做', exact: true }).click();
  await expect(page.getByTestId('roll-note')).toHaveCount(2);
  await page.getByRole('button', { name: '▶ 试听编曲', exact: true }).click();
