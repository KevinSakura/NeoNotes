  await page.getByRole('button', { name: /02\s*演奏与编辑/ }).click();
  await expect(page.getByLabel('导入 MIDI', { exact: true })).toBeEnabled();
  await page.getByLabel('导入 MIDI', { exact: true }).setInputFiles({ name: downloaded.suggestedFilename(), mimeType: 'audio/midi', buffer: await readFile(file!) });
