test('simultaneous keys and focus loss release and retain held recording notes', async ({ page }) => {
  await page.goto('/'); await createSong(page, '同时按键与失焦');
  await page.getByRole('button', { name: '● 开始录制', exact: true }).click();
  await expect(page.getByRole('button', { name: '■ 停止录制', exact: true })).toBeVisible();
  await page.keyboard.down('a'); await page.keyboard.down('s');
  await expect(page.locator('.key.pressed')).toHaveCount(2);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await expect(page.locator('.key.pressed')).toHaveCount(0);
  await expect(page.getByTestId('record-info')).toContainText('2 个音符');
  await expect(page.getByRole('button', { name: '● 开始录制', exact: true })).toBeVisible();
  await page.keyboard.up('a'); await page.keyboard.up('s');
  await page.getByRole('button', { name: '把片段加入编曲 →', exact: true }).click();
  await expect(page.getByTestId('roll-note')).toHaveCount(2);
  await page.getByRole('button', { name: '保存歌曲', exact: true }).click();
  await expect(page.getByTestId('save-state')).toContainText('已写入歌曲目录');
});
